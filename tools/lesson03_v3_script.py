RULE = "────────────────────────────────────────"


def _speech(line):
    if line == "":
        return ""
    if line.startswith("("):
        return line
    return "“" + line + "”"


def note_text(i):
    n = NOTES[i]
    out = ["[%s]  %s" % (n["time"], n["title"]), RULE, "이 장의 목적 · " + n["goal"], ""]
    out.append("● 이렇게 말해 보세요")
    prev_blank = False
    for line in n["say"]:
        s = _speech(line)
        if s == "":
            if not prev_blank:
                out.append("")
            prev_blank = True
        else:
            out.append(s)
            prev_blank = False
    if n.get("ask"):
        out += ["", "● 학생에게 물어보기"]
        for q, a in n["ask"]:
            out.append("Q. " + q)
            out.append("   → " + a)
    if n.get("run"):
        out += ["", "● 활동 시간 운영"]
        for t, d in n["run"]:
            out.append("[%s] %s" % (t, d.replace("**", "").replace("`", "")))
    if n.get("level"):
        out += ["", "● 수준에 따라"]
        out += ["· " + x for x in n["level"]]
    if n.get("obs"):
        out += ["", "● 관계자 앞에서"]
        out += ["· " + x for x in n["obs"]]
    if n.get("tips"):
        out += ["", "● 진행 팁"]
        out += ["· " + x.replace("`", "") for x in n["tips"]]
    if n.get("next"):
        out += ["", "● 다음 장으로", _speech(n["next"])]
    return "\n".join(out)


